// mean of dim items → 0..100 (rev flips on the test's own scale max)
export const dimPct = (test, answers, dim) => {
  const max = (test.options ?? LIKERT).length
  const idx = test.questions.map((q, i) => [q, i]).filter(([q]) => q.d === dim)
  const vals = idx.map(([q, i]) => (q.rev ? max + 1 - answers[i] : answers[i]))
  return Math.round(((vals.reduce((a, b) => a + b, 0) / vals.length) - 1) / (max - 1) * 100)
}

// raw 0-based sum (for banded clinical scales)
export const rawSum = (test, answers) => {
  const max = (test.options ?? LIKERT).length
  return test.questions.reduce((s, q, i) => s + ((q.rev ? max + 1 - answers[i] : answers[i]) - 1), 0)
}

export const band = (sum, bands) => bands.find(([limit]) => sum <= limit)

