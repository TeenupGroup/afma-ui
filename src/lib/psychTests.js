// Result <-> URL hash (shareable, no DB)
export const encodeResult = (answers) => btoa(answers.join(','))
export const decodeResult = (hash, maxV = 5) => {
  try {
    const arr = atob(hash).split(',').map(Number)
    return arr.every((n) => n >= 1 && n <= maxV) ? arr : null
  } catch { return null }
}
